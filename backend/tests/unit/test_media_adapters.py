@pytest.fixture()
def real_png_bytes() -> bytes:
    """A real 64x48 PNG generated by OpenCV itself."""
    image = np.full((48, 64, 3), 128, dtype=np.uint8)
    ok, buffer = cv2_imencode_png(image)
    assert ok
    return buffer.tobytes()


def cv2_imencode_png(image: np.ndarray) -> tuple[bool, np.ndarray]:
    """Encode an image to PNG via OpenCV (imported lazily)."""
    import cv2

    return cv2.imencode(".png", image)


def test_forensics_reports_dimensions_and_low_risk(real_png_bytes: bytes) -> None:
    """A clean synthetic image must report its size and low tamper risk."""
    report = OpenCvForensicsAdapter().analyze(real_png_bytes)
    assert isinstance(report, ForensicsReport)
    assert report.signals["width"] == 64
    assert report.signals["height"] == 48
    assert report.signals["reencode_signal"] == "low"
    assert 0.0 <= report.risk_score <= 1.0


def test_forensics_risk_is_bounded(real_png_bytes: bytes) -> None:
    """Risk score must stay within [0, 1] regardless of image content."""
    report = OpenCvForensicsAdapter().analyze(real_png_bytes)
    assert 0.0 <= report.risk_score <= 1.0


def test_decode_image_rejects_garbage_bytes() -> None:
    """Undecodable bytes must raise MediaProcessingError."""
    with pytest.raises(MediaProcessingError, match="cannot decode"):
        decode_image(b"this is not an image")


def test_forensics_rejects_garbage_bytes() -> None:
    """The adapter must surface decode failures as MediaProcessingError."""
    with pytest.raises(MediaProcessingError, match="cannot decode"):
        OpenCvForensicsAdapter().analyze(b"garbage" * 100)


