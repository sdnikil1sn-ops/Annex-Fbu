# ----------------------------------------------------------------------
# Fake pytesseract module
# ----------------------------------------------------------------------


def make_fake_pytesseract(
    *,
    text: list[str] | None = None,
    conf: list[str] | None = None,
    missing_binary: bool = False,
) -> types.ModuleType:
    """Build a stand-in ``pytesseract`` module with configurable behavior.

    Args:
        text: Per-cell text values returned by ``image_to_data``.
        conf: Per-cell confidence values ("-1" means no text).
        missing_binary: If True, ``get_tesseract_version`` raises the
            not-found error the adapter must translate.
    """
    fake = types.ModuleType("pytesseract")
    fake.TesseractNotFoundError = type("TesseractNotFoundError", (RuntimeError,), {})

    if missing_binary:

        def get_version() -> None:
            raise fake.TesseractNotFoundError("binary missing")

    else:
        get_version = lambda: types.SimpleNamespace(  # noqa: E731
            __str__=lambda self: "5.4.0"
        )

    class Output:
        DICT = 3

    fake.Output = Output

    def image_to_data(image: Any, lang: str, output_type: Any) -> dict[str, list[str]]:
        return {"text": text or [], "conf": conf or []}

    fake.get_tesseract_version = get_version
    fake.image_to_data = image_to_data
    return fake


@pytest.fixture()
def fake_pytesseract(monkeypatch: pytest.MonkeyPatch) -> types.ModuleType:
    """Inject the fake pytesseract module for the whole test module."""
    fake = make_fake_pytesseract()
    monkeypatch.setitem(sys.modules, "pytesseract", fake)
    return fake


# ----------------------------------------------------------------------
# Tesseract OCR adapter
# ----------------------------------------------------------------------


def test_ocr_extracts_text_and_confidence(
    fake_pytesseract: types.ModuleType,
    real_png_bytes: bytes,
) -> None:
    """Words with real confidence must join into text with a mean score."""
    fake_pytesseract.image_to_data = lambda image, lang, output_type: {
        "text": ["Hello", "", "world", "unreadable"],
        "conf": ["95", "-1", "80", "-1"],
    }
    adapter = TesseractOcrAdapter(languages="eng")
    result = adapter.extract_text(real_png_bytes)
    assert result.text == "Hello world"
    assert result.confidence == pytest.approx(87.5)
    assert result.language == "eng"


def test_ocr_empty_text_yields_none_confidence(
    fake_pytesseract: types.ModuleType,
    real_png_bytes: bytes,
) -> None:
    """No recognizable text must yield an empty string and None confidence."""
    adapter = TesseractOcrAdapter()
    result = adapter.extract_text(real_png_bytes)
    assert result == OcrResult(text="", confidence=None, language="eng")


def test_ocr_missing_binary_raises_configuration_error(monkeypatch: pytest.MonkeyPatch) -> None:
    """A missing tesseract binary must surface as ConfigurationError."""
    monkeypatch.setitem(sys.modules, "pytesseract", make_fake_pytesseract(missing_binary=True))
    with pytest.raises(ConfigurationError, match="tesseract binary not found"):
        TesseractOcrAdapter()


