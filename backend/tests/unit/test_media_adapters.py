def test_mock_ocr_counts_calls_and_returns_fixed_result() -> None:
    """The OCR mock must count calls and return its fixed result."""
    adapter = MockOcrAdapter()
    result = adapter.extract_text(b"image")
    assert result.text == "mock ocr text"
    assert result.confidence == 0.9
    assert adapter.calls == 1
    adapter.extract_text(b"another")
    assert adapter.calls == 2


def test_mock_forensics_counts_calls() -> None:
    """The forensics mock must count calls and return a fixed report."""
    adapter = MockForensicsAdapter()
    report = adapter.analyze(b"image")
    assert report.risk_score == 0.0
    assert report.signals == {"mock": True}
    adapter.analyze(b"image")
    assert adapter.calls == 2
