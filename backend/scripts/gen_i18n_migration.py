def sql_for(locale: str, rows: list[tuple[str, str, str]]) -> str:
    values = ",\n        ".join(
        f"('{ns}', '{key}', {_sql_literal(value)}, 'none')" for ns, key, value in rows
    )
    return f"""insert into public.i18n_translations (locale_id, namespace, key, value, plural_rule, version)
select l.id, t.namespace, t.key, t.value, t.plural_rule, 1
from public.i18n_locales l,
     (values
        {values}
     ) as t (namespace, key, value, plural_rule)
where l.code = '{locale}'
on conflict (locale_id, namespace, key) do nothing;
"""


def _sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    lines = [
        "-- =====================================================================",
        "-- ANNEX — Migration 20260815000006: Hindi + Tamil locales and the",
        "-- missing English base keys (auth, analysis modes, settings, subtitles).",
        "-- Adding a language is a data change, never a rebuild (ADR-0007).",
        "-- =====================================================================",
        "",
        "insert into public.i18n_locales (code, enabled, fallback_code) values",
        "    ('hi', true, 'en'),",
        "    ('ta', true, 'en')",
        "on conflict (code) do nothing;",
        "",
        "-- English — keys the earlier seeds did not define (fallback root).",
        sql_for("en", EN),
        "-- Hindi.",
        sql_for("hi", HI),
        "-- Tamil.",
        sql_for("ta", TA),
    ]
    out = Path(__file__).resolve().parent.parent.parent / "supabase" / "migrations" / "20260815000006_i18n_hi_ta.sql"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(EN)} en, {len(HI)} hi, {len(TA)} ta rows)")


